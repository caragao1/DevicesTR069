function normalize(name: string) {
  return name.trim().toLowerCase().replace(/\s+/g, " ");
}

function monogram(name: string) {
  const trimmed = name.trim();
  if (trimmed.length <= 4) return trimmed.toUpperCase();
  const words = trimmed.split(/[\s-]+/).filter(Boolean);
  if (words.length >= 2) {
    return (words[0][0] + words[1][0]).toUpperCase();
  }
  return trimmed.slice(0, 2).toUpperCase();
}

export function ManufacturerIcon({
  manufacturer,
  className,
}: {
  manufacturer: string;
  className?: string;
}) {
  const brand = BRAND_ICONS[normalize(manufacturer)];

  if (brand) {
    return (
      <svg viewBox="0 0 24 24" className={className} fill={brand.hex}>
        <path d={brand.path} />
      </svg>
    );
  }

  return (
    <span
      className={`flex items-center justify-center font-sans font-bold text-stone-500 dark:text-slate-400 ${className ?? ""}`}
      style={{ fontSize: "0.7em" }}
    >
      {monogram(manufacturer)}
    </span>
  );
}
